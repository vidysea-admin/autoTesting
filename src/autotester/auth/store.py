"""The auth store seam (M29/M30, mongo-store U6a): what accounts, groups, sessions and
project grants need from storage, as typed operations instead of SQL.

`AuthStore` hands out one `AuthTx` per read or write transaction. Every method is one of
the statements the auth modules used to run inline; the business rules (who may touch whom,
first-admin, password checks) stay in `accounts`, `groups`, `access` and `sessions`, which
call only this Protocol. Nothing here returns or accepts a password hash except
`login_record` and the two `*_password_hash` writers, so a list API cannot leak one (M30).
`store_sqlite.py` is the SQLite implementation; a Mongo one (U6b) implements the same
contract without assuming multi-document transactions.
"""

from __future__ import annotations

from contextlib import AbstractContextManager
from typing import Protocol

from autotester.schema.auth import Group, Principal, User


class AuthTx(Protocol):
    """One consistent view of the store. Writes are meaningful only on a transaction."""

    # -- users ---------------------------------------------------------------------
    def count_users(self) -> int: ...
    def get_user(self, user_id: int) -> User | None: ...
    def find_user(self, email: str) -> User | None: ...
    def login_record(self, email: str) -> tuple[User, str] | None:
        """The account and its stored password hash, for the login check only."""
    def list_users(self) -> list[User]: ...
    def user_manager_emails(self) -> list[str]:
        """Enabled accounts holding users.manage and access.approve@<any scope> (F2)."""
    def known_user_ids(self) -> set[int]: ...
    def insert_user(self, email: str, password_hash: str) -> int:
        """A new account with a fresh immutable generation; returns its id."""
    def set_password_hash(self, user_id: int, password_hash: str) -> bool: ...
    def enable_with_password_hash(self, user_id: int, password_hash: str) -> None: ...
    def set_disabled(self, user_id: int, disabled: bool) -> bool: ...
    def set_display_name(self, user_id: int, name: str) -> bool: ...
    def delete_user(self, user_id: int) -> bool:
        """Sessions, memberships and project grants of the account go with it."""

    # -- groups and memberships ----------------------------------------------------
    def admin_group_id(self) -> int | None: ...
    def admin_has_member(self) -> bool: ...
    def list_groups(self) -> list[Group]: ...
    def get_group(self, group_id: int) -> Group | None: ...
    def known_group_ids(self) -> set[int]: ...
    def group_name_taken(self, name: str, except_id: int | None = None) -> bool: ...
    def insert_group(self, name: str) -> int: ...
    def rename_group(self, group_id: int, name: str) -> None: ...
    def delete_group(self, group_id: int) -> bool: ...
    def group_permissions(self, group_id: int) -> set[str]: ...
    def set_group_permissions(self, group_id: int, permissions: set[str]) -> None: ...
    def group_member_ids(self, group_id: int) -> set[int]: ...
    def set_group_members(self, group_id: int, user_ids: set[int]) -> None: ...
    def user_group_ids(self, user_id: int) -> set[int]: ...
    def set_user_groups(self, user_id: int, group_ids: set[int]) -> None: ...
    def add_membership(self, user_id: int, group_id: int,
                       ignore_existing: bool = False) -> None: ...
    def ensure_an_admin_remains(self, after_delete: bool = False) -> None:
        """AU9: raises `db.LastAdmin` when the change would leave no enabled admin."""

    # -- sessions (only the sha256 of a token is ever stored) -----------------------
    def insert_session(self, digest: str, user_id: int, created_at: str,
                       expires_at: str) -> None: ...
    def purge_sessions_before(self, now: str) -> None: ...
    def delete_session(self, digest: str) -> None: ...
    def delete_session_if_expired(self, digest: str, now: str) -> None: ...
    def delete_user_sessions(self, user_id: int) -> None: ...
    def has_session(self, digest: str) -> bool: ...
    def live_principal(self, digest: str, now: str) -> Principal | None:
        """The principal of an unexpired session whose account is enabled."""

    # -- project grants ------------------------------------------------------------
    def project_people(self, slug: str) -> dict[str, set[str]]:
        """relation value -> emails, for the relations that have anyone."""
    def replace_project_owner(self, slug: str, user_id: int) -> None: ...
    def add_project_relation(self, slug: str, user_id: int, relation: str) -> None: ...
    def remove_project_relation(self, slug: str, user_id: int, relation: str) -> None: ...


class AuthStore(Protocol):
    def exists(self) -> bool:
        """A read that finds no store must not create one (AU16)."""
    def reading(self) -> AbstractContextManager[AuthTx]: ...
    def transaction(self) -> AbstractContextManager[AuthTx]:
        """One write transaction; rolled back whole on any exception."""


def auth_store() -> AuthStore:
    """The active auth store. SQLite today; U6b adds the Mongo implementation."""
    from autotester.auth.store_sqlite import SqliteAuthStore
    return SqliteAuthStore()
